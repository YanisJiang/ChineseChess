import { lineFromPath } from './lineFromPath'
import type { StudyLine } from './types'

function mid(
  id: string,
  title: string,
  summary: string,
  prefix: string[],
  plies: { uci: string; benefit: string; main?: boolean }[],
  endComment: string,
): StudyLine {
  return lineFromPath({
    id,
    phase: 'middlegame',
    title,
    summary,
    prefix,
    plies: plies.map((p, i) => ({ ...p, main: p.main ?? i === 0 })),
    endComment,
  })
}

