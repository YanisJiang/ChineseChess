function op(
  id: string,
  title: string,
  summary: string,
  plies: { uci: string; benefit: string; main?: boolean }[],
  endComment: string,
): StudyLine {
  return lineFromPath({
    id,
    phase: 'opening',
    title,
    summary,
    prefix: [],
    plies: plies.map((p, i) => ({ ...p, main: p.main ?? i === 0 })),
    endComment,
  })
}

